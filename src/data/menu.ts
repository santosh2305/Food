import type { MenuItem, Dietary } from '../types';
type Entry = [name: string, rupees: number | null, portion?: string, description?: string];
function section(
  category: string,
  sourcePage: number,
  dietary: Dietary | undefined,
  entries: Entry[],
): MenuItem[] {
  return entries.map(([name, rupees, portion, description]) => ({
    id: `${category}-${name}`.toLowerCase().replace(/[^a-z0-9]+/g, '-'),
    name,
    category,
    price: rupees === null ? null : rupees * 100,
    portion,
    description,
    dietary,
    available: rupees !== null,
    sourcePage,
  }));
}
